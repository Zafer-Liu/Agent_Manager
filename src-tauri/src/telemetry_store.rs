fn format_conversation(messages: &[(String, String)]) -> String {
    const MAX_CONVERSATION_CHARS: usize = 48_000;
    let text = messages
        .iter()
        .filter(|(role, _)| matches!(role.as_str(), "user" | "assistant"))
        .filter_map(|(role, content)| {
            // L0 清洗：先剥离宿主注入的上下文包裹（system-reminder/meta 等），
            // 再按角色剔除助手思考块；两个角色都只保留人说的话和 Agent 的回复。
            let cleaned = strip_injected_context(content);
            let content = if role == "assistant" {
                strip_thinking_blocks(&cleaned).trim().to_string()
            } else {
                cleaned.trim().to_string()
            };
            (!content.is_empty()).then(|| {
                format!(
                    "[{}]\n{}",
                    if role == "user" { "用户" } else { "助手" },
                    content
                )
            })
        })
        .collect::<Vec<_>>()
        .join("\n\n");
    if text.chars().count() <= MAX_CONVERSATION_CHARS {
        text
    } else {
        format!(
            "{}\n\n[对话过长，已截断]",
            text.chars()
                .take(MAX_CONVERSATION_CHARS)
                .collect::<String>()
        )
    }
}

/// 宿主环境注入的上下文包裹（Kimi 的 `<meta/>`、各 Agent 的
/// `<system-reminder>` / `<agent-context>` 等）是 harness 对模型说的话，
/// 不是用户对 Agent 说的话，一律不得进入 L0。只剥离成对闭合或自闭合的
/// 完整块；未闭合的标签保留原文，避免误删用户刻意引用的内容。
///
/// pub(crate)：转录读取器在计算内容指纹前就要应用同一规则，否则
/// 「指纹未变」的旧行永远不会被新清洗规则重录。
pub(crate) fn strip_injected_context(text: &str) -> String {
    const PAIRED_TAGS: [&str; 7] = [
        "system-reminder",
        "agent-context",
        "user_info",
        "identity_context",
        "environment_context",
        "relevant_memory_details",
        "relevant_memories",
    ];
    let mut cleaned = text.to_string();
    // 自闭合 <meta ... /> 注入。
    while let Some(start) = cleaned.find("<meta") {
        let boundary = cleaned[start + 5..].chars().next();
        if !matches!(boundary, Some(' ' | '\t' | '\n' | '\r' | '/')) {
            break;
        }
        let Some(end) = cleaned[start..].find("/>") else {
            break;
        };
        cleaned.replace_range(start..start + end + 2, "");
    }
    for tag in PAIRED_TAGS {
        let open = format!("<{tag}");
        let close = format!("</{tag}>");
        while let Some(start) = cleaned.find(&open) {
            let boundary = cleaned[start + open.len()..].chars().next();
            if !matches!(boundary, Some(' ' | '\t' | '\n' | '\r' | '>' | '/')) {
                break;
            }
            let Some(end) = cleaned[start..].find(&close) else {
                break;
            };
            cleaned.replace_range(start..start + end + close.len(), "");
        }
    }
    // 折叠剥离后残留的连续空行。
    let mut out = String::with_capacity(cleaned.len());
    let mut blank_lines = 0u32;
    for line in cleaned.lines() {
        if line.trim().is_empty() {
            blank_lines += 1;
            if blank_lines > 1 {
                continue;
            }
        } else {
            blank_lines = 0;
        }
        if !out.is_empty() {
            out.push('\n');
        }
        out.push_str(line);
    }
    out.trim().to_string()
}

fn truncate_chars(text: &str, max_chars: usize) -> String {
    if text.chars().count() <= max_chars {
        return text.to_string();
    }
    format!(
        "{}\n[内容已截断]",
        text.chars().take(max_chars).collect::<String>()
    )
}

fn keyword_terms(query: &str) -> Vec<String> {
    let lower = query.to_lowercase();
    let mut terms = Vec::new();
    let mut latin = String::new();
    let mut cjk = Vec::new();
    for character in lower.chars() {
        if character.is_ascii_alphanumeric() || character == '_' || character == '-' {
            latin.push(character);
            continue;
        }
        if latin.len() >= 2 {
            terms.push(std::mem::take(&mut latin));
        } else {
            latin.clear();
        }
        if ('\u{4e00}'..='\u{9fff}').contains(&character) {
            cjk.push(character);
        }
    }
    if latin.len() >= 2 {
        terms.push(latin);
    }
    for pair in cjk.windows(2) {
        terms.push(pair.iter().collect());
    }
    terms.sort();
    terms.dedup();
    terms
}

fn keyword_score(text: &str, query: &str, terms: &[String]) -> f64 {
    let haystack = text.to_lowercase();
    let matches = terms
        .iter()
        .filter(|term| haystack.contains(term.as_str()))
        .count();
    let coverage = if terms.is_empty() {
        0.0
    } else {
        matches as f64 / terms.len() as f64
    };
    let exact_bonus = haystack
        .contains(&query.to_lowercase())
        .then_some(0.35)
        .unwrap_or(0.0);
    // Keep the direct phrase match dominant, then add a bounded semantic-alias
    // signal.  This stays entirely offline while allowing natural switches
    // between common Agent Manager terms such as "偏好" / "约束" or "MCP" /
    // "共享记忆".
    let aliases = local_search_aliases(query);
    let alias_matches = aliases
        .iter()
        .filter(|term| haystack.contains(term.as_str()))
        .count();
    let alias_score = if aliases.is_empty() {
        0.0
    } else {
        alias_matches as f64 / aliases.len() as f64 * 0.42
    };
    if matches == 0 && alias_matches == 0 {
        return 0.0;
    }
    coverage + exact_bonus + alias_score
}

/// Small, transparent local equivalence set for the vocabulary users actually
/// use in Agent Manager. It is deliberately not a remote embedding service:
/// all matching happens against the SQLite ledger and never leaves the device.
fn local_search_aliases(query: &str) -> Vec<String> {
    let normalized = query.to_lowercase();
    let groups: [(&[&str], &[&str]); 7] = [
        (
            &["记忆", "memory", "上下文"],
            &["长期记忆", "共享记忆", "会话要点", "上下文"],
        ),
        (
            &["偏好", "约束", "习惯", "profile"],
            &["用户偏好", "长期偏好", "约束", "用户习惯"],
        ),
        (
            &["skill", "技能", "skill库"],
            &["共享 skill", "技能库", "skill library", "已发布 skill"],
        ),
        (
            &["mcp", "共享记忆", "注入"],
            &["模型上下文协议", "共享记忆", "recall_memory", "agent 注入"],
        ),
        (
            &["hook", "监听", "会话", "对话"],
            &["hook", "完整对话", "会话记录", "自动沉淀"],
        ),
        (
            &["token", "用量", "消耗"],
            &["token", "输入", "输出", "用量统计"],
        ),
        (&["检索", "搜索", "查找"], &["检索", "搜索", "召回", "匹配"]),
    ];
    let mut aliases = groups
        .into_iter()
        .filter(|(triggers, _)| {
            triggers
                .iter()
                .any(|trigger| normalized.contains(&trigger.to_lowercase()))
        })
        .flat_map(|(_, aliases)| aliases.iter().map(|alias| alias.to_lowercase()))
        .filter(|alias| !normalized.contains(alias))
        .collect::<Vec<_>>();
    aliases.sort();
    aliases.dedup();
    aliases
}

fn get_str<'a>(payload: &'a Value, keys: &[&str]) -> Option<&'a str> {
    keys.iter()
        .find_map(|key| payload.get(*key).and_then(Value::as_str))
}

/// Persist every parseable external timestamp in one sortable UTC format.
/// The UI deliberately renders this instant in the user's local time zone;
/// raw `+00:00` values are never shown as if they were local wall-clock time.
fn canonical_timestamp(value: &str) -> String {
    chrono::DateTime::parse_from_rfc3339(value)
        .map(|time| {
            time.with_timezone(&chrono::Utc)
                .to_rfc3339_opts(chrono::SecondsFormat::Millis, true)
        })
        .unwrap_or_else(|_| chrono::Utc::now().to_rfc3339())
}

/// Returns (provenance, input, output, cached).  Only values supplied by an
/// adapter are labelled reported; absent values remain unavailable rather than
/// being presented as a misleading estimate.
fn extract_usage(payload: &Value) -> (&'static str, i64, i64, i64) {
    let usage = payload.get("usage").unwrap_or(payload);
    let input = get_i64(usage, &["input_tokens", "prompt_tokens"]);
    let output = get_i64(usage, &["output_tokens", "completion_tokens"]);
    let cached = get_i64(usage, &["cached_tokens", "cache_read_input_tokens"]);
    if input.is_some() || output.is_some() || cached.is_some() {
        (
            "reported",
            input.unwrap_or(0),
            output.unwrap_or(0),
            cached.unwrap_or(0),
        )
    } else {
        ("unavailable", 0, 0, 0)
    }
}

/// Index the native transcript locations once per manual refresh instead of
/// repeatedly walking the disk for every Hook event.  The traversal is bounded
/// to the native session folders and matches exact session identifiers.
fn discover_native_transcripts(
    sessions: &[(String, String, Option<PathBuf>)],
) -> HashMap<(String, String), PathBuf> {
    let wanted = |source: &str| {
        sessions
            .iter()
            .filter(|(kind, _, _)| kind == source)
            .map(|(_, session_id, _)| session_id.clone())
            .collect::<HashSet<_>>()
    };
    let mut found = HashMap::new();
    for source in crate::agent_sources::AGENT_SOURCE_IDS {
        let wanted = wanted(source);
        if wanted.is_empty() {
            continue;
        }
        for root in crate::agent_sources::transcript_roots(source) {
            scan_transcript_tree(&root, source, &wanted, &mut found);
        }
    }
    found
}

/// Enumerate native transcript files even if an Agent did not send a Hook.
/// This is a metadata-only discovery pass; callers decide whether a file has
/// changed and therefore needs its content parsed.  Codex keeps older session
/// files under `archived_sessions`, which is just as authoritative as its live
/// `sessions` tree for usage history.  Transcript roots come from the agent
/// source registry so per-device overrides apply to every supported Agent.
fn discover_all_native_transcripts() -> Vec<(String, String, PathBuf)> {
    let mut latest = HashMap::<(String, String), (std::time::SystemTime, PathBuf)>::new();
    for source in crate::agent_sources::AGENT_SOURCE_IDS {
        for root in crate::agent_sources::transcript_roots(source) {
            scan_all_transcript_tree(root.as_path(), source, &mut latest);
        }
    }
    latest
        .into_iter()
        .map(|((source, session_id), (_, path))| (source, session_id, path))
        .collect()
}

fn scan_all_transcript_tree(
    root: &Path,
    source: &str,
    found: &mut HashMap<(String, String), (std::time::SystemTime, PathBuf)>,
) {
    let mut pending = vec![root.to_path_buf()];
    let mut visited = 0usize;
    while let Some(directory) = pending.pop() {
        if visited >= 20_000 {
            break;
        }
        let Ok(entries) = std::fs::read_dir(directory) else {
            continue;
        };
        for entry in entries.flatten() {
            visited += 1;
            let path = entry.path();
            if path.is_dir() {
                pending.push(path);
                continue;
            }
            if path.extension().and_then(|extension| extension.to_str()) != Some("jsonl") {
                continue;
            }
            let Some(session_id) = transcript_session_id(source, &path) else {
                continue;
            };
            let modified = entry
                .metadata()
                .ok()
                .and_then(|metadata| metadata.modified().ok())
                .unwrap_or(std::time::SystemTime::UNIX_EPOCH);
            let key = (source.to_string(), session_id);
            if found
                .get(&key)
                .map(|(current, _)| modified > *current)
                .unwrap_or(true)
            {
                found.insert(key, (modified, path));
            }
        }
    }
}

fn transcript_session_id(source: &str, path: &Path) -> Option<String> {
    crate::agent_sources::session_id_for_path(source, path)
}

fn scan_transcript_tree(
    root: &Path,
    source: &str,
    wanted: &HashSet<String>,
    found: &mut HashMap<(String, String), PathBuf>,
) {
    let mut pending = vec![root.to_path_buf()];
    // A safety ceiling prevents an unrelated, malformed profile directory
    // from making the Memory Center refresh indefinitely.
    let mut visited = 0usize;
    while let Some(dir) = pending.pop() {
        if visited >= 20_000
            || found.keys().filter(|(kind, _)| kind == source).count() >= wanted.len()
        {
            break;
        }
        let Ok(entries) = std::fs::read_dir(dir) else {
            continue;
        };
        for entry in entries.flatten() {
            visited += 1;
            let path = entry.path();
            if path.is_dir() {
                pending.push(path);
                continue;
            }
            if path.extension().and_then(|extension| extension.to_str()) != Some("jsonl") {
                continue;
            }
            // 会话 id 推导统一走注册表：Claude/Qoder/WorkBuddy 用文件 stem，
            // Codex 用文件名末尾 UUID，MiniMax/Kimi 用会话目录名。
            let session_id = crate::agent_sources::session_id_for_path(source, &path)
                .filter(|id| wanted.contains(id));
            if let Some(session_id) = session_id {
                found
                    .entry((source.to_string(), session_id.to_string()))
                    .or_insert(path);
            }
        }
    }
}

fn transcript_usage(value: &Value) -> Option<TranscriptUsage> {
    let input_tokens = get_i64(value, &["input_tokens", "prompt_tokens"]);
    let output_tokens = get_i64(value, &["output_tokens", "completion_tokens"]);
    if input_tokens.is_none() && output_tokens.is_none() {
        return None;
    }
    Some(TranscriptUsage {
        input_tokens: input_tokens.unwrap_or(0),
        output_tokens: output_tokens.unwrap_or(0),
        cached_tokens: get_i64(
            value,
            &[
                "cached_input_tokens",
                "cache_read_input_tokens",
                "cached_tokens",
            ],
        )
        .unwrap_or(0),
    })
}

fn usage_record_id(source: &str, session_id: &str, kind: &str, identity: &str) -> String {
    let digest = Sha256::digest(identity.as_bytes());
    format!(
        "{source}:v1:{session_id}:{kind}:{}",
        hex(&digest)[..20].to_string()
    )
}

/// Reconstruct per-response observations for every local agent format that
/// exposes provider counters. The collection is fully rebuilt for the one
/// session inside the same SQLite transaction, making a manual refresh
/// idempotent even when native logs are appended or rewritten.
fn read_transcript_usage_records(
    source: &str,
    session_id: &str,
    path: &Path,
) -> Vec<TranscriptUsageRecord> {
    match source {
        "codex" => read_codex_usage_records(session_id, path),
        "claude" => read_claude_usage_records(session_id, path),
        "workbuddy" => read_workbuddy_usage_records(session_id, path),
        // Qoder does not write provider counters today, but its user/assistant
        // rows can use the same transparent transcript estimate at a
        // message-level boundary. They remain explicitly marked estimated.
        "qoder" => read_qoder_usage_records(session_id, path),
        "minimax" => read_minimax_usage_records(session_id, path),
        "kimi" => read_kimi_usage_records(session_id, path),
        _ => Vec::new(),
    }
}

fn read_codex_usage_records(session_id: &str, path: &Path) -> Vec<TranscriptUsageRecord> {
    let Ok(file) = std::fs::File::open(path) else {
        return Vec::new();
    };
    let mut records = Vec::new();
    let mut current_model = None;
    let mut high_water: Option<TranscriptUsage> = None;
    let mut last_without_total: Option<TranscriptUsage> = None;
    for line in BufReader::new(file).lines().map_while(Result::ok) {
        let Ok(entry) = serde_json::from_str::<Value>(&line) else {
            continue;
        };
        let timestamp = get_str(&entry, &["timestamp", "occurred_at", "time"]).map(str::to_string);
        let Some(payload) = entry.get("payload") else {
            continue;
        };
        if entry.get("type").and_then(Value::as_str) == Some("turn_context") {
            current_model = get_str(payload, &["model", "model_name"])
                .map(str::to_string)
                .or_else(|| {
                    payload
                        .get("context")
                        .and_then(|context| get_str(context, &["model", "model_name"]))
                        .map(str::to_string)
                });
            continue;
        }
        if entry.get("type").and_then(Value::as_str) != Some("event_msg")
            || payload.get("type").and_then(Value::as_str) != Some("token_count")
        {
            continue;
        }
        let Some(info) = payload.get("info") else {
            continue;
        };
        let total = info.get("total_token_usage").and_then(transcript_usage);
        let last = info.get("last_token_usage").and_then(transcript_usage);
        let (delta, identity) = if let Some(total) = total {
            let previous = high_water.unwrap_or(TranscriptUsage {
                input_tokens: 0,
                output_tokens: 0,
                cached_tokens: 0,
            });
            // Cumulative counters may be repeated by rate-limit refreshes. A
            // non-increasing snapshot is never another billable response.
            if total.input_tokens + total.output_tokens
                <= previous.input_tokens + previous.output_tokens
            {
                continue;
            }
            high_water = Some(total);
            (
                TranscriptUsage {
                    input_tokens: total.input_tokens.saturating_sub(previous.input_tokens),
                    output_tokens: total.output_tokens.saturating_sub(previous.output_tokens),
                    cached_tokens: total.cached_tokens.saturating_sub(previous.cached_tokens),
                },
                format!(
                    "total:{}:{}:{}",
                    total.input_tokens, total.output_tokens, total.cached_tokens
                ),
            )
        } else if let Some(last) = last {
            // Last-token snapshots are only used when a cumulative counter is
            // absent. Consecutive identical snapshots are rate-limit repeats.
            if last_without_total
                .map(|previous| {
                    previous.input_tokens == last.input_tokens
                        && previous.output_tokens == last.output_tokens
                        && previous.cached_tokens == last.cached_tokens
                })
                .unwrap_or(false)
            {
                continue;
            }
            last_without_total = Some(last);
            (
                last,
                format!(
                    "last:{}:{}:{}:{}",
                    timestamp.as_deref().unwrap_or(""),
                    last.input_tokens,
                    last.output_tokens,
                    last.cached_tokens
                ),
            )
        } else {
            continue;
        };
        if delta.input_tokens == 0 && delta.output_tokens == 0 && delta.cached_tokens == 0 {
            continue;
        }
        records.push(TranscriptUsageRecord {
            record_id: usage_record_id("codex", session_id, "token_count", &identity),
            occurred_at: timestamp,
            model: current_model.clone(),
            input_tokens: delta.input_tokens,
            output_tokens: delta.output_tokens,
            cached_tokens: delta.cached_tokens.min(delta.input_tokens),
        });
    }
    records
}

fn read_claude_usage_records(session_id: &str, path: &Path) -> Vec<TranscriptUsageRecord> {
    let Ok(file) = std::fs::File::open(path) else {
        return Vec::new();
    };
    let mut seen = HashSet::new();
    BufReader::new(file)
        .lines()
        .map_while(Result::ok)
        .filter_map(|line| {
            let entry = serde_json::from_str::<Value>(&line).ok()?;
            if entry.get("type").and_then(Value::as_str) != Some("assistant")
                || entry.get("isSidechain").and_then(Value::as_bool) == Some(true)
            {
                return None;
            }
            let message = entry.get("message")?;
            let usage = message.get("usage")?;
            let identity = message
                .get("id")
                .and_then(Value::as_str)
                .map(str::to_string)
                .unwrap_or_else(|| serde_json::to_string(usage).unwrap_or_default());
            if !seen.insert(identity.clone()) {
                return None;
            }
            let cache_read = get_i64(usage, &["cache_read_input_tokens"]).unwrap_or(0);
            let cache_write = get_i64(usage, &["cache_creation_input_tokens"]).unwrap_or(0);
            let input_tokens =
                get_i64(usage, &["input_tokens"]).unwrap_or(0) + cache_read + cache_write;
            let output_tokens = get_i64(usage, &["output_tokens"]).unwrap_or(0);
            ((input_tokens > 0 || output_tokens > 0) as bool).then_some(TranscriptUsageRecord {
                record_id: usage_record_id("claude", session_id, "message", &identity),
                occurred_at: get_str(&entry, &["timestamp", "occurred_at", "time"])
                    .map(str::to_string),
                model: get_str(message, &["model", "model_name"]).map(str::to_string),
                input_tokens,
                output_tokens,
                cached_tokens: cache_read,
            })
        })
        .collect()
}

