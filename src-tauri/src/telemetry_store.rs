static SHARED: OnceLock<Arc<TelemetryStore>> = OnceLock::new();

pub fn init_shared(store: TelemetryStore) {
    let _ = SHARED.set(Arc::new(store));
}

pub fn shared_store() -> Option<Arc<TelemetryStore>> {
    SHARED.get().cloned()
}

